/** The lucide component for a bot avatar icon name, or undefined when the name is not in the closed list. */
export function avatarIconComponent(name: string | null | undefined): LucideIcon | undefined {
  if (!name) return undefined;
  return (AVATAR_ICON_COMPONENTS as Record<string, LucideIcon>)[name];
}
